package javaAssignments;//WAP on switch case problem with char

public class Assi17C_SwitchCase3 {

	public static void main(String[] args) 
	{
		char input = 'F';
		switch(input)
		{
		case 'M':
			System.out.println("gender is male");
			break;
		case 'F':
			System.out.println("gender is female");
			break;
			default:
				System.out.println("your input is wrong");

				
			
		}

	}

}
