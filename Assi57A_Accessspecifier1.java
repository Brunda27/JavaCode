package javaAssignments;
//WAP to access Public, protected, default & private variables within a class(static modifier)
public class Assi57A_Accessspecifier1
{
	public static int a = 150;
	protected static int b = 250;
	 static int c = 350;
	private static int d = 450;

	public static void main(String[] args)
	{
		System.out.println(a);
		System.out.println(b);
		System.out.println(c);
		System.out.println(d);

		
	}
}
